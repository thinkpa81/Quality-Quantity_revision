"""Verify aggregate claims from locally held benchmark prediction records.

This is a diagnostic calculation, not a new predictive-model fit or new
bootstrap sampling run. Inputs are the user's own trusted test_predictions.pkl
and disjoint_history_predictions.pkl, generated by the complete analysis
pipeline. No respondent records or identifiers are written to the output.

Example (replace the private path with the local pipeline output):
    python python/verify_retained_predictions.py --results-dir results \
        --private-dir /path/to/local/private --output-dir verification_run
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.special import expit, logit
from scipy.optimize import brentq, root
from sklearn.metrics import roc_auc_score, average_precision_score

from verify_aggregate_release import verify as verify_aggregate_release

def independent_calibration(y,p,w=None):
 y=np.asarray(y,float);z=logit(np.clip(np.asarray(p,float),1e-6,1-1e-6));w=np.ones(len(y)) if w is None else np.asarray(w,float)
 a=brentq(lambda a:np.sum(w*(y-expit(z+a))),-40,40,xtol=1e-13)
 def score(b):
  e=w*(y-expit(b[0]+b[1]*z));return np.array([e.sum(),(e*z).sum()])
 def jac(b):
  p=expit(b[0]+b[1]*z);v=w*p*(1-p);return -np.array([[v.sum(),(v*z).sum()],[(v*z).sum(),(v*z*z).sum()]])
 fit=root(score,[0,1],jac=jac,tol=1e-11)
 assert np.max(np.abs(score(fit.x)))<1e-6
 return {'calibration_intercept':a,'calibration_joint_intercept':fit.x[0],'calibration_slope':fit.x[1]}

def verify(results_dir: Path, private_dir: Path) -> dict:
    RES = results_dir
    PRIVATE = private_dir
    report = {
        "release": "2026-10-29",
        "status": "PASS",
        "scope": "Arithmetic and diagnostic-estimation checks using retained predictions; no new predictive model fit or bootstrap draw generation",
        "checks": {},
        "qualifications": [],
    }
    def read(name):
        return pd.read_csv(RES / name)
    t=pd.read_pickle(PRIVATE/'test_predictions.pkl');m=read('model_calibration_metrics.csv');models=['logistic','random_forest','xgboost','catboost','forward_stack'];rows=[]
    for model in models:
     for method in ['raw','platt','isotonic']:
      col=model if method=='raw' else model+'_'+method;actual=independent_calibration(t.exit_label_t1,t[col]);r=m[(m.partition=='test')&(m.model==model)&(m.method==method)].iloc[0]
      errs={k:abs(float(v)-float(r[k])) for k,v in actual.items()};assert max(errs.values())<1e-8,(model,method,errs)
      rows.append({'model':model,'method':method,'max_absolute_coefficient_difference':max(errs.values()),'recomputed':actual})
    report['checks']['independent_calibration']={'status':'PASS','variants':len(rows),'coefficients_checked':len(rows)*3,'tolerance_absolute':1e-8,'maximum_error':max(x['max_absolute_coefficient_difference'] for x in rows),'rows':rows,'definitions':{'calibration_intercept':'CITL; intercept with logit(p) offset and slope fixed at1','calibration_joint_intercept':'Intercept estimated jointly with calibration slope'}}
    weighted=read('survey_weighted_metrics.csv');errors=[]
    for _,r in weighted.iterrows():
     g=t if str(r.wave)=='pooled' else t[t.wave.eq(int(r.wave))]
     g=g[g.weight18_cross.notna() & g.weight18_cross.gt(0)];y=g.exit_label_t1.to_numpy();p=g[r.model].to_numpy();w=g.weight18_cross.to_numpy()
     vals={'n':len(g),'events':int(y.sum()),'event_rate':np.average(y,weights=w),'effective_n_kish':w.sum()**2/(w@w),'roc_auc':roc_auc_score(y,p,sample_weight=w),'pr_auc':average_precision_score(y,p,sample_weight=w),'brier':np.average((p-y)**2,weights=w)}
     assert all(np.isclose(v,r[k],atol=1e-10,rtol=1e-12) for k,v in vals.items())
     errors.append(max(abs(v-r[k]) for k,v in vals.items()))
    report['checks']['weighted_evaluation']={'status':'PASS','rows':len(weighted),'metrics_per_row':7,'max_abs_difference':max(errors),'pooled_rows':int(weighted[weighted.wave.eq('pooled')].n.iloc[0]),'excluded_missing_or_nonpositive_weight_rows':len(t)-int(weighted[weighted.wave.eq('pooled')].n.iloc[0]),'scope':'Positive integrated2018 cross-sectional weights on observed-followup test rows; no survey-weighted training and no full survey-design variance'}
    h=pd.read_pickle(PRIVATE/'disjoint_history_predictions.pkl');groups=read('disjoint_history_groups.csv');errs=[]
    for _,r in groups.iterrows():
     g=h[h.arm.eq(r.arm)]
     if r.history_definition!='all':
      value=str(r.history).lower()=='true';g=g[g[r.history_definition].eq(value)]
     vals={'n':len(g),'events':int(g.exit_label_t1.sum()),'people':g.pid.nunique(),'roc_auc':roc_auc_score(g.exit_label_t1,g[r.method]),'pr_auc':average_precision_score(g.exit_label_t1,g[r.method]),'brier':np.mean((g[r.method]-g.exit_label_t1)**2)}
     assert all(np.isclose(v,r[k],rtol=1e-12,atol=1e-12) for k,v in vals.items()),(r.history_definition,r.history,r.arm)
     errs.append(max(abs(v-r[k]) for k,v in vals.items()))
    co=read('disjoint_history_contrasts.csv');dr=read('disjoint_history_bootstrap_replicates.csv')
    for _,r in co.iterrows():
     q=dr
     for k in ['history_definition','contrast','method','metric']:q=q[q[k].eq(r[k])]
     assert len(q)==500 and q.replicate.nunique()==500
     lo,hi=q.difference.quantile([.025,.975]);assert np.allclose([lo,hi],[r.lower,r.upper],rtol=0,atol=1e-12)
    report['checks']['history_stratified_fixed_model']={'status':'PASS','group_rows':len(groups),'group_metrics_per_row':6,'max_abs_difference':max(errs),'paired_history_interval_rows':len(co),'replicates_per_interval':500,'raw_roc_contrasts':co[(co.history_definition=='eligible_training_history')&(co.method=='raw')&(co.metric=='roc_auc')].to_dict('records')}
    orig=read('all_model_origins.csv');fold=read('origin_forward_folds.csv');assert len(orig)==30
    assert set(orig.train_end)=={14,17} and orig.groupby('train_end').model.nunique().eq(5).all()
    assert (fold.latest_base_outcome<fold.oof_start).all()
    report['checks']['earlier_origin_coverage']={'status':'PASS','origins':[14,17],'learners_per_origin':5,'probability_variants_per_learner':3,'rows':len(orig),'windows':{'14':{'train':[1,14],'validation':[15,17],'test':[18,20]},'17':{'train':[1,17],'validation':[18,20],'test':[21,23]}},'internal_oof_strict_labels_before_scoring':True,'scope':'Two earlier expanding-training origins, not exhaustive rolling-window or prospective release-calendar validation'}
    sh=read('shap_rank_stability.csv');assert len(sh)==3 and sh.same_model_iterations.eq(300).all() and sh.sample_rows.eq(1000).all()
    report['checks']['shap_stability']={'status':'PASS','source_rows':sh.to_dict('records'),'scope':'Three disjoint1000-row samples of one fixed primary300-iteration CatBoost; no retraining, cross-time, causal or independent-feature-effect guarantee'}
    report['checks']['aggregate_reverification']=verify_aggregate_release(RES)
    report['qualifications']=[
     {'topic':'person dependence','finding':'Person-cluster pairing and household-component sensitivity address specified observed clustering. Fits, maps, thresholds and observed historical waves remain fixed.'},
     {'topic':'temporal validation','finding':'Primary completed-wave boundary and stricter forward-OOF boundary are distinct and explicit. Release delays, within-year ordering and future common shocks remain outside scope.'},
     {'topic':'calibration terminology','finding':'CITL is the reported offset calibration intercept, not an independent additional statistic. Joint intercept is separately stored, and slopes are jointly estimated.'},
     {'topic':'person-disjoint score','finding':'Primary vs disjoint results use different training/evaluation populations. Lower point performance cannot identify person memorisation or the causal effect of training overlap.'},
    ]
    report['source_hashes']={name:hashlib.sha256((RES/name).read_bytes()).hexdigest() for name in ['model_calibration_metrics.csv','survey_weighted_metrics.csv','disjoint_history_groups.csv','disjoint_history_contrasts.csv','disjoint_history_bootstrap_replicates.csv','all_model_origins.csv','origin_forward_folds.csv','shap_rank_stability.csv']}
    if report["checks"]["aggregate_reverification"]["status"] != "PASS":
        report["status"] = "FAIL"
    return report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results-dir", type=Path, required=True,
                        help="Aggregate results directory from the released pipeline")
    parser.add_argument("--private-dir", type=Path, required=True,
                        help="Local private pipeline output containing the two prediction pickle files")
    parser.add_argument("--output-dir", type=Path, required=True,
                        help="Directory for aggregate verification JSON reports")
    args = parser.parse_args()
    if not __debug__:
        parser.error("Run without Python -O so all numerical checks remain active")
    args.output_dir.mkdir(parents=True, exist_ok=True)
    try:
        report = verify(args.results_dir, args.private_dir)
    except (AssertionError, ValueError, KeyError, OSError) as exc:
        report = {"status": "FAIL", "error_type": type(exc).__name__, "error": str(exc)}
    destination = args.output_dir / "statistical_evidence_check.json"
    destination.write_text(json.dumps(report, indent=2, ensure_ascii=False,
        default=lambda value: value.item() if hasattr(value, "item") else str(value)) + "\n")
    if "aggregate_reverification" in report.get("checks", {}):
        (args.output_dir / "aggregate_reverification.json").write_text(json.dumps(
            report["checks"]["aggregate_reverification"], indent=2, ensure_ascii=False) + "\n")
    print(f"{report['status']}: retained-prediction verification")
    for name, check in report.get("checks", {}).items():
        print(f"  {check.get('status', 'UNKNOWN')}: {name}")
    return 0 if report["status"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
